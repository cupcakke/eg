import {readFileSync, writeFileSync, readdirSync, statSync, mkdirSync} from 'node:fs'
import {join, dirname, resolve, relative} from 'node:path'
import {fileURLToPath} from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const srcRoot = join(root, 'src')
const outFile = join(root, 'docs', 'api-reference.md')

function walk(dir) {
	const out = []
	for (const name of readdirSync(dir).sort()) {
		if (name === 'shaders.gen.imba' || name === 'shaders.gen.mjs') continue
		const full = join(dir, name)
		const st = statSync(full)
		if (st.isDirectory()) out.push(...walk(full))
		else if (name.endsWith('.imba')) out.push(full)
	}
	return out
}

function extractProps(lines) {
	const props = []
	for (const line of lines) {
		const m = /^\s*prop\s+([A-Za-z_$][\w$]*)\s*(?:=\s*([^@]+?))?\s*(@watch)?\s*$/.exec(line)
		if (m) props.push({name: m[1], def: (m[2] || '').trim(), watch: !!m[3]})
		const g = /^\s*static\s+get\s+([A-Za-z_$][\w$]*)\s*$/.exec(line)
		if (g) props.push({name: `static ${g[1]}`, def: '(getter)', watch: false})
	}
	return props
}

function extractMethods(lines, exportedClasses) {
	const methods = new Map()
	let currentClass = null
	let classIndent = 0
	for (const line of lines) {
		const cm = /^export\s+class\s+([A-Za-z_$][\w$]*)/.exec(line)
		if (cm) {
			currentClass = cm[1]
			methods.set(currentClass, [])
			continue
		}
		const dm = /^\s+def\s+([A-Za-z_$][\w$]*)\s*(.*)$/.exec(line)
		if (dm && currentClass && !/^(constructor|render|mount|unmount|build)$/.test(dm[1])) {
			const sig = dm[2].trim()
			methods.get(currentClass).push({name: dm[1], sig})
		}
	}
	return methods
}

function describeFile(file) {
	const rel = relative(srcRoot, file)
	const lines = readFileSync(file, 'utf8').split('\n')
	const block = {file: rel, tags: [], exports: [], methods: new Map()}
	const propsByTag = new Map()
	let currentTag = null
	for (const line of lines) {
		const tm = /^tag\s+([a-z0-9-]+)/.exec(line)
		if (tm) {
			currentTag = tm[1]
			propsByTag.set(currentTag, [])
			continue
		}
		if (currentTag && /^\S/.test(line)) currentTag = null
		if (currentTag) {
			const pm = /^\s*prop\s+([A-Za-z_$][\w$]*)\s*(?:=\s*([^@]+?))?\s*(@watch)?\s*$/.exec(line)
			if (pm) propsByTag.get(currentTag).push({name: pm[1], def: (pm[2] || '').trim()})
		}
		const em = /^export\s+(?:default\s+)?(class|def|const|let)\s+([A-Za-z_$][\w$]*)\s*(.*)$/.exec(line)
		if (em) block.exports.push({kind: em[1], name: em[2], sig: em[3].trim()})
		const sm = /^export\s+class\s+([A-Za-z_$][\w$]*)/.exec(line)
		if (sm) block.methods.set(sm[1], [])
	}
	for (const [tag, props] of propsByTag) block.tags.push({name: tag, props})
	const clsMethods = extractMethods(lines)
	for (const [cls, list] of clsMethods) if (block.methods.has(cls)) block.methods.set(cls, list)
	return block
}

