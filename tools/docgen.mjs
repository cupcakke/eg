for (const b of blocks) {
	if (b.tags.length === 0 && b.exports.length === 0) continue
	const dir = b.file.split('/')[0]
	if (!groups.has(dir)) groups.set(dir, [])
	groups.get(dir).push(b)
}

for (const [group, list] of [...groups.entries()].sort()) {
	out.push(`## ${group}/`)
	out.push('')
	for (const b of list.sort((a, c) => a.file.localeCompare(c.file))) {
		out.push(`### ${b.file}`)
		out.push('')
		for (const tag of b.tags) {
			out.push(`Element \`<${tag.name}>\``)
			out.push('')
			if (tag.props.length > 0) {
				out.push('| property | default |')
				out.push('|---|---|')
				for (const p of tag.props) out.push(`| \`${p.name}\` | ${p.def ? `\`${p.def}\`` : '—'} |`)
				out.push('')
			}
		}
		for (const e of b.exports) {
			out.push(`- \`${e.kind} ${e.name}${e.sig && !e.sig.startsWith('{') ? ' ' + e.sig.split('\n')[0] : ''}\``)
		}
		for (const [cls, methods] of b.methods) {
			if (methods.length > 0) {
				out.push('')
				out.push(`\`${cls}\` methods:`)
				out.push('')
				for (const m of methods) out.push(`- \`${m.name}${m.sig ? ' ' + m.sig : ''}\``)
			}
		}
		out.push('')
	}
}

